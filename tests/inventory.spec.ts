import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import type { Project } from '../src/core/schema'

async function readProject(page: Page): Promise<Project> {
  return page.evaluate(async () => {
    const url = '/src/state/projectStore.ts'
    return (await import(url)).useProjectStore.getState().project
  })
}

async function openInventory(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '05 Inventory', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hardware inventory', exact: true })).toBeVisible()
}

async function addHardware(page: Page, model = 'Office switch', quantity = '2', ports = '4') {
  await page.getByRole('button', { name: 'Add hardware', exact: true }).click()
  await expect(page.getByLabel('Model', { exact: true })).toBeFocused()
  await page.getByLabel('Model', { exact: true }).fill(model)
  await page.getByLabel('Category', { exact: true }).fill('Switch')
  await page.getByLabel('Available quantity').fill(quantity)
  await page.getByLabel('Unit cost', { exact: true }).fill('125.50')
  await page.getByLabel('Ports per unit').fill(ports)
  await page.getByLabel('Capabilities (comma separated)').fill('VLAN, routing')
  await page.getByRole('button', { name: 'Save hardware', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Hardware added.')
}

async function seedDevice(page: Page) {
  await page.evaluate(async () => {
    const url = '/src/state/projectStore.ts'
    const { useProjectStore } = await import(url)
    const id = useProjectStore.getState().addDevice({ name: 'Core switch', role: 'switch', scope: 'HQ' }, { x: 0, y: 0 })
    useProjectStore.getState().addBulkPorts(id, { prefix: 'eth', start: 1, count: 10, speed: '1 Gbps', media: 'copper' })
  })
}

test('inventory CRUD, planned shortages, costs, validation and deletion protection', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await openInventory(page)
  await expect(page.getByText('No hardware recorded.', { exact: false })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Allocate hardware', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Add hardware', exact: true }).click()
  await page.getByRole('button', { name: 'Save hardware', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('model')
  expect((await readProject(page)).hardwareItems).toHaveLength(0)
  await page.getByLabel('Model', { exact: true }).press('Escape')
  await expect(page.getByRole('button', { name: 'Add hardware', exact: true })).toBeFocused()
  await addHardware(page)
  const id = (await readProject(page)).hardwareItems[0]!.id
  const stock = page.getByRole('region', { name: 'Hardware stock', exact: true })
  await expect(stock).toContainText('251.00')
  await expect(stock).toContainText('VLAN, routing')
  await page.getByRole('button', { name: 'Allocate hardware', exact: true }).click()
  await page.getByLabel('Assign to', { exact: true }).selectOption('device')
  await page.getByRole('button', { name: 'Save allocation', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Choose a device')
  await page.getByLabel('Assign to', { exact: true }).selectOption('scope')
  await page.getByLabel('Site / scope', { exact: true }).fill('Branch')
  await page.getByLabel('Allocation quantity', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Save allocation', exact: true }).click()
  await expect(stock).toContainText('Short 1')
  await expect(page.getByRole('heading', { name: 'Hardware issues (1)' })).toBeVisible()
  const allocationId = (await readProject(page)).allocations[0]!.id
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete hardware Office switch', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('active allocations')
  expect((await readProject(page)).hardwareItems).toHaveLength(1)
  await page.getByRole('button', { name: 'Edit hardware Office switch', exact: true }).click()
  await page.getByLabel('Available quantity').fill('')
  await page.getByRole('button', { name: 'Apply hardware', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Enter the available quantity')
  await page.getByLabel('Available quantity').fill('-1')
  await page.getByRole('button', { name: 'Apply hardware', exact: true }).click()
  expect((await readProject(page)).hardwareItems[0]!.quantityAvailable).toBe(2)
  await page.getByLabel('Model', { exact: true }).fill('Access switch')
  await page.getByLabel('Available quantity').fill('4')
  await page.getByLabel('Available quantity').press('Enter')
  await expect(stock).toContainText('1 free')
  expect((await readProject(page)).hardwareItems[0]!.id).toBe(id)
  await expect(page.getByRole('heading', { name: /Hardware issues/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit allocation Access switch / Branch', exact: true }).click()
  await page.getByLabel('Allocation quantity', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Apply allocation', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('quantity')
  expect((await readProject(page)).allocations[0]!.quantity).toBe(3)
  await page.getByLabel('Allocation quantity', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Apply allocation', exact: true }).click()
  expect((await readProject(page)).allocations[0]!.id).toBe(allocationId)
  const snapshot = await readProject(page)
  await page.getByRole('button', { name: '01 Calculator', exact: true }).click()
  await page.getByRole('button', { name: '05 Inventory', exact: true }).click()
  expect(await readProject(page)).toEqual(snapshot)
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Delete allocation Access switch / Branch', exact: true }).click()
  expect((await readProject(page)).allocations).toHaveLength(1)
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete allocation Access switch / Branch', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Allocate hardware', exact: true })).toBeFocused()
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Delete hardware Access switch', exact: true }).click()
  expect((await readProject(page)).hardwareItems).toHaveLength(1)
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete hardware Access switch', exact: true }).click()
  expect((await readProject(page)).hardwareItems).toHaveLength(0)
  await expect(page.getByRole('button', { name: 'Add hardware', exact: true })).toBeFocused()
  expect(errors).toEqual([])
})

test('device allocations sum units and models and follow topology deletion', async ({ page }) => {
  await openInventory(page)
  await seedDevice(page)
  await expect(page.getByRole('region', { name: 'Device port capacity', exact: true })).toContainText('Unassigned')
  await addHardware(page)
  await page.getByRole('button', { name: 'Allocate hardware', exact: true }).click()
  await page.getByLabel('Assign to', { exact: true }).selectOption('device')
  await page.getByRole('button', { name: 'Save allocation', exact: true }).click()
  const ports = page.getByRole('region', { name: 'Device port capacity', exact: true })
  await expect(ports).toContainText('Short 6 ports')
  await addHardware(page, 'Expansion', '2', '2')
  await page.getByRole('button', { name: 'Allocate hardware', exact: true }).click()
  await page.getByLabel('Hardware model', { exact: true }).selectOption({ label: 'Expansion' })
  await page.getByLabel('Assign to', { exact: true }).selectOption('device')
  await page.getByLabel('Allocation quantity', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Save allocation', exact: true }).click()
  await expect(ports).toContainText('Short 2 ports')
  await page.getByRole('button', { name: 'Edit allocation Office switch / Core switch', exact: true }).click()
  await page.getByLabel('Allocation quantity', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Apply allocation', exact: true }).click()
  await expect(ports).toContainText('2 spare ports')
  await page.getByRole('button', { name: 'Edit allocation Expansion / Core switch', exact: true }).click()
  await page.getByLabel('Hardware model', { exact: true }).selectOption({ label: 'Office switch' })
  await page.getByLabel('Assign to', { exact: true }).selectOption('scope')
  await page.getByLabel('Site / scope', { exact: true }).fill('Warehouse')
  await page.getByRole('button', { name: 'Apply allocation', exact: true }).click()
  await expect(ports).toContainText('Short 2 ports')
  await page.getByRole('button', { name: '03 Physical', exact: true }).click()
  await page.getByLabel('Inspect device', { exact: true }).selectOption({ label: 'Core switch (HQ)' })
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete device', exact: true }).click()
  await page.getByRole('button', { name: '05 Inventory', exact: true }).click()
  const project = await readProject(page)
  expect(project.allocations).toHaveLength(1)
  expect(project.allocations[0]!.scope).toBe('Warehouse')
  expect(project.hardwareItems).toHaveLength(2)
})

test('inventory reflows, supports keyboard forms, and passes axe in both themes', async ({ page }) => {
  await openInventory(page)
  await addHardware(page)
  await seedDevice(page)
  await page.getByRole('button', { name: 'Allocate hardware', exact: true }).click()
  await page.getByLabel('Site / scope', { exact: true }).fill('HQ')
  await page.getByRole('button', { name: 'Save allocation', exact: true }).click()
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') await page.getByRole('button', { name: 'Use dark theme', exact: true }).click()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.screenshot({ path: `test-results/inventory-${theme}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Edit hardware Office switch', exact: true }).click()
    await expect(page.getByLabel('Model', { exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(page.getByLabel('Category', { exact: true })).toBeFocused()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Edit hardware Office switch', exact: true })).toBeFocused()
    await page.getByRole('button', { name: 'Edit allocation Office switch / HQ', exact: true }).click()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.getByLabel('Hardware model', { exact: true }).press('Escape')
  }
  await page.getByRole('button', { name: 'Use light theme', exact: true }).click()
  for (const width of [320, 390, 600, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.getByRole('button', { name: 'Add hardware', exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByLabel('Model', { exact: true }).press('Escape')
  }
  await page.setViewportSize({ width: 390, height: 1000 })
  await page.screenshot({ path: 'test-results/inventory-mobile.png', fullPage: true })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  await page.getByRole('button', { name: 'Allocate hardware', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('region', { name: 'Hardware stock', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => page.getByRole('region', { name: 'Hardware stock', exact: true }).evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
})
