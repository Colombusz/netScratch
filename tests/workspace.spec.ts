test('keyboard navigation and both themes pass automated accessibility checks', async ({ page }) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to workspace' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main')).toBeFocused()
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') await page.getByRole('button', { name: 'Use dark theme' }).click()
    await page.getByRole('button', { name: 'Calculate', exact: true }).click()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.getByRole('button', { name: 'Planner', exact: false }).click()
    await page.getByRole('button', { name: 'Generate subnets' }).click()
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.getByRole('button', { name: 'Edit Staff' }).click()
    expect(await page.getByRole('button', { name: 'Delete Staff' }).evaluate((button) => button.getBoundingClientRect().height)).toBeLessThanOrEqual(48)
    expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Calculator', exact: false }).click()
  }
  await page.getByRole('button', { name: 'Use light theme' }).click()
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme', 'light')
})

test('mobile and enlarged text reflow without page overflow', async ({ page }) => {
  await page.goto('/')
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('button', { name: 'Planner', exact: false }).click()
    await page.getByRole('button', { name: 'Generate subnets' }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Edit Staff' }).click()
    await expect(page.getByLabel('Subnet name')).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    if (width === 390) {
      await page.getByRole('region', { name: 'Subnet allocation table' }).evaluate((table) => { table.scrollLeft = 0 })
      await page.screenshot({ path: 'test-results/planner-mobile.png', fullPage: true })
    }
  }
  await page.setViewportSize({ width: 390, height: 900 })
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Calculator', exact: false }).click()
  await page.getByRole('button', { name: 'Calculate', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
