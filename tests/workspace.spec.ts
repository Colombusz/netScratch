test('reserved blocks, parent validation, cancellation, and deletion update free space', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Planner', exact: false }).click()
  await page.getByRole('button', { name: 'Apply parent' }).click()
  await expect(page.getByText('256 / 256 addresses free')).toBeVisible()
  await page.getByRole('button', { name: 'Reserve range' }).click()
  await page.getByLabel('Subnet CIDR', { exact: true }).fill('192.168.10.0/27')
  await page.getByRole('button', { name: 'Apply subnet' }).click()
  await expect(page.getByText('224 / 256 addresses free')).toBeVisible()
  await page.getByRole('button', { name: 'Generate subnets' }).click()
  await expect(page.getByRole('row', { name: /Staff/ })).toContainText('192.168.10.128/25')
  await expect(page.getByRole('row', { name: /Admin/ })).toContainText('192.168.10.64/26')
  await expect(page.getByRole('row', { name: /Guests/ })).toContainText('192.168.10.32/27')
  await expect(page.getByText('No unused addresses remain')).toBeVisible()
  await page.getByLabel('Parent block').fill('192.168.10.0/25')
  await page.getByRole('button', { name: 'Apply parent' }).click()
  await expect(page.getByRole('alert')).toContainText('outside parent')
  await expect(page.getByText('0 / 256 addresses free')).toBeVisible()
  await page.getByLabel('Parent block').fill('192.168.10.0/24')
  await page.getByRole('button', { name: 'Edit Reserved range' }).click()
  await page.getByLabel('Subnet name').press('Escape')
  await expect(page.getByRole('heading', { name: 'Subnet inspector' })).not.toBeVisible()
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Delete Reserved range' }).click()
  await expect(page.getByRole('row', { name: /Reserved range/ })).toBeVisible()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Delete Reserved range' }).click()
  await expect(page.getByText('32 / 256 addresses free')).toBeVisible()
})

test('insufficient space and invalid requirements have actionable errors', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Planner', exact: false }).click()
  await page.getByLabel('Usable addresses 2', { exact: true }).fill('100')
  await page.getByLabel('Usable addresses 3', { exact: true }).fill('50')
  await page.getByRole('button', { name: 'Generate subnets' }).click()
  await expect(page.getByRole('alert')).toContainText('Insufficient space for Guests')
  await expect(page.getByRole('row', { name: /Staff/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /Admin/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /Guests/ })).not.toBeVisible()
  await page.getByLabel('Usable addresses 1', { exact: true }).fill('-1')
  await page.getByRole('button', { name: 'Generate subnets' }).click()
  await expect(page.getByRole('alert').first()).toContainText('hosts')
  await expect(page.getByRole('row', { name: /Staff/ })).toBeVisible()
  for (let count = 3; count > 0; count--) await page.getByRole('button', { name: `Remove requirement ${count}` }).click()
  await expect(page.getByText('No requirements.')).toBeVisible()
  await page.getByRole('button', { name: 'Generate subnets' }).click()
  await expect(page.getByRole('alert').first()).toContainText('Add at least one segment')
  await page.getByRole('button', { name: 'Add segment' }).click()
  await page.getByLabel('Segment 1', { exact: true }).fill('Transit')
  await page.getByLabel('Usable addresses 1', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Generate subnets' }).click()
  await expect(page.getByRole('row', { name: /Transit/ })).toContainText('192.168.10.0/31')
})

