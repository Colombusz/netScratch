import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('calculator accepts masks, rejects invalid input, and explains /31 and /32', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByText('Enter an address and calculate')).toBeVisible()
  await page.getByRole('button', { name: 'Calculate', exact: true }).click()
  await expect(page.getByText('192.168.10.126', { exact: true })).toBeVisible()
  await expect(page.getByText('126 usable addresses')).toBeVisible()
  const input = page.getByLabel('IPv4 address and prefix or mask')
  await input.fill('192.168.10.9 255.255.255.0')
  await expect(page.getByText('Input changed.')).toBeVisible()
  await input.press('Enter')
  await expect(page.getByText('254 usable addresses')).toBeVisible()
  await input.fill('1.2.3.4/255.0.255.0')
  await input.press('Enter')
  await expect(page.getByRole('alert')).toContainText('contiguous')
  await expect(page.getByText('254 usable addresses')).not.toBeVisible()
  for (const [value, expected] of [['10.0.0.0/31', '2 usable addresses'], ['10.0.0.1/32', '1 usable address']]) {
    await input.fill(value!)
    await input.press('Enter')
    await expect(page.getByText(expected!, { exact: true })).toBeVisible()
  }
  await input.fill('')
  await input.press('Enter')
  await expect(page.getByRole('alert')).toContainText('Enter an IPv4')
  expect(errors).toEqual([])
})

